-- Baseline schema, version 1.
--
-- Captured from the database Hibernate had built up to this point, then given
-- explicit constraint names in place of the generated ones (fk3dchyur..., uk4dcdf...)
-- so future migrations can refer to them by name.
--
-- Existing databases are baselined at this version rather than having it run
-- against them, so they keep their original generated names. Anything created
-- from scratch — production included — gets the names below.

CREATE TABLE users (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(255),
    email      VARCHAR(255) NOT NULL,
    password   VARCHAR(255),
    phone      VARCHAR(255),
    address    VARCHAR(255),
    role       VARCHAR(255),
    enabled    BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    CONSTRAINT uk_users_email UNIQUE (email),
    CONSTRAINT ck_users_role CHECK (role IN ('ADMIN', 'ELDER', 'HELPER'))
);

CREATE TABLE helper_profiles (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            BIGINT NOT NULL,
    bio                VARCHAR(1000),
    city               VARCHAR(255),
    hourly_rate        NUMERIC(10, 2) NOT NULL,
    -- Room for 0.00 to 9.99; ratings are on a five-point scale.
    average_rating     NUMERIC(3, 2) NOT NULL,
    completed_bookings INTEGER NOT NULL,
    verified           BOOLEAN NOT NULL,
    accepting_bookings BOOLEAN NOT NULL,
    CONSTRAINT uk_helper_profiles_user UNIQUE (user_id),
    CONSTRAINT fk_helper_profiles_user FOREIGN KEY (user_id) REFERENCES users (id)
);

-- Element collection for HelperProfile.offeredServices.
CREATE TABLE helper_services (
    helper_profile_id BIGINT NOT NULL,
    service_type      VARCHAR(255) NOT NULL,
    PRIMARY KEY (helper_profile_id, service_type),
    CONSTRAINT fk_helper_services_profile FOREIGN KEY (helper_profile_id)
        REFERENCES helper_profiles (id),
    CONSTRAINT ck_helper_services_type CHECK (service_type IN (
        'HOSPITAL_VISIT', 'GROCERY_SHOPPING', 'HOUSE_HELP',
        'COMPANIONSHIP', 'MEDICATION_PICKUP', 'TRANSPORT'))
);

CREATE TABLE bookings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    elder_id        BIGINT NOT NULL,
    helper_id       BIGINT NOT NULL,
    service_type    VARCHAR(255) NOT NULL,
    status          VARCHAR(255) NOT NULL,
    scheduled_start TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    scheduled_end   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    actual_start    TIMESTAMP(6) WITH TIME ZONE,
    actual_end      TIMESTAMP(6) WITH TIME ZONE,
    -- Snapshotted at booking time: a later rate change must not reprice an
    -- arrangement both sides already agreed.
    hourly_rate     NUMERIC(10, 2) NOT NULL,
    estimated_total NUMERIC(10, 2) NOT NULL,
    final_total     NUMERIC(10, 2),
    service_address VARCHAR(255),
    notes           VARCHAR(1000),
    created_at      TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_bookings_elder  FOREIGN KEY (elder_id)  REFERENCES users (id),
    CONSTRAINT fk_bookings_helper FOREIGN KEY (helper_id) REFERENCES users (id),
    CONSTRAINT ck_bookings_service_type CHECK (service_type IN (
        'HOSPITAL_VISIT', 'GROCERY_SHOPPING', 'HOUSE_HELP',
        'COMPANIONSHIP', 'MEDICATION_PICKUP', 'TRANSPORT')),
    CONSTRAINT ck_bookings_status CHECK (status IN (
        'REQUESTED', 'ACCEPTED', 'REJECTED', 'IN_PROGRESS', 'COMPLETED', 'CANCELLED'))
);

CREATE TABLE messages (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL,
    sender_id  BIGINT NOT NULL,
    body       VARCHAR(2000) NOT NULL,
    read_at    TIMESTAMP(6) WITH TIME ZONE,
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_messages_booking FOREIGN KEY (booking_id) REFERENCES bookings (id),
    CONSTRAINT fk_messages_sender  FOREIGN KEY (sender_id)  REFERENCES users (id)
);

-- Threads are read oldest-first for one booking; this is that query.
CREATE INDEX idx_messages_booking_created ON messages (booking_id, created_at);

CREATE TABLE notifications (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recipient_id BIGINT NOT NULL,
    type         VARCHAR(255) NOT NULL,
    title        VARCHAR(120) NOT NULL,
    body         VARCHAR(500) NOT NULL,
    -- Nullable: reserved for future notification types with no booking behind them.
    booking_id   BIGINT,
    read_flag    BOOLEAN NOT NULL,
    created_at   TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_notifications_recipient FOREIGN KEY (recipient_id) REFERENCES users (id),
    CONSTRAINT ck_notifications_type CHECK (type IN (
        'BOOKING_REQUESTED', 'BOOKING_ACCEPTED', 'BOOKING_REJECTED',
        'BOOKING_STARTED', 'BOOKING_COMPLETED', 'BOOKING_CANCELLED',
        'MESSAGE_RECEIVED'))
);

-- The notification centre lists newest-first for one recipient; the badge counts
-- unread for that same recipient.
CREATE INDEX idx_notifications_recipient_created ON notifications (recipient_id, created_at);
