-- Email verification and password reset.

-- Accounts created before this migration predate verification. Marking them
-- verified keeps every existing user able to book; only new signups confirm.
ALTER TABLE users ADD COLUMN email_verified BOOLEAN NOT NULL DEFAULT FALSE;
UPDATE users SET email_verified = TRUE;

-- Set when the password changes. Tokens issued before it are refused, so a reset
-- signs out every other device, including one an attacker may be holding.
ALTER TABLE users ADD COLUMN credentials_changed_at TIMESTAMP(6) WITH TIME ZONE;

-- One-time codes sent by email. Only a hash of the code is stored, so a leaked
-- table cannot be used to verify an address or take over an account.
CREATE TABLE verification_codes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT NOT NULL,
    purpose     VARCHAR(32) NOT NULL,
    code_hash   VARCHAR(64) NOT NULL,
    attempts    INTEGER NOT NULL,
    expires_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    consumed_at TIMESTAMP(6) WITH TIME ZONE,
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    CONSTRAINT fk_verification_codes_user FOREIGN KEY (user_id) REFERENCES users (id),
    CONSTRAINT ck_verification_codes_purpose CHECK (purpose IN ('EMAIL_VERIFICATION', 'PASSWORD_RESET'))
);

-- Every lookup is "the newest code of this purpose for this user".
CREATE INDEX idx_verification_codes_user_purpose ON verification_codes (user_id, purpose, created_at);
