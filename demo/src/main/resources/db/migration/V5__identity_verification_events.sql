CREATE TABLE identity_verification_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subject_user_id BIGINT NOT NULL REFERENCES users(id),
    actor_user_id BIGINT NOT NULL REFERENCES users(id),
    status VARCHAR(24) NOT NULL,
    note VARCHAR(500),
    created_at TIMESTAMP(6) WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_identity_verification_events_subject
    ON identity_verification_events(subject_user_id, created_at);

ALTER TABLE users ADD COLUMN identity_verified_at TIMESTAMP(6) WITH TIME ZONE;
ALTER TABLE users ADD COLUMN identity_verification_updated_at TIMESTAMP(6) WITH TIME ZONE;

UPDATE users
SET identity_verified_at = CURRENT_TIMESTAMP
WHERE identity_verification_status = 'VERIFIED';

UPDATE users
SET identity_verification_updated_at = COALESCE(identity_verified_at, created_at)
WHERE identity_verification_updated_at IS NULL;